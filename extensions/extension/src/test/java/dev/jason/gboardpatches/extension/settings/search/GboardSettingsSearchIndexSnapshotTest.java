package dev.jason.gboardpatches.extension.settings.search;

import android.content.Context;

import org.junit.Assert;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.RuntimeEnvironment;
import org.robolectric.annotation.Config;
import org.robolectric.annotation.ConscryptMode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Keeps the packaged settings search index equal to what the feature tree shows. After changing
 * settings pages, regenerate it with
 * {@code .\gradlew.bat :extensions:extension:testDebugUnitTest
 * --tests "*GboardSettingsSearchIndexSnapshotTest*" -PupdateSettingsSearchIndex=true}.
 */
@RunWith(RobolectricTestRunner.class)
@Config(sdk = 33, manifest = Config.NONE,
        shadows = GboardSettingsSearchIndexCrawler.TokenText.class)
@ConscryptMode(ConscryptMode.Mode.OFF)
public final class GboardSettingsSearchIndexSnapshotTest {
    private static final String UPDATE_PROPERTY = "gboard.updateSettingsSearchIndex";
    private static final String DATA_SOURCE =
            "src/main/java/dev/jason/gboardpatches/extension/settings/search/"
                    + "GboardSettingsSearchIndexData.java";

    @Test
    public void packagedIndexMatchesFeatureTree() throws IOException {
        Context context = RuntimeEnvironment.getApplication();
        GboardSettingsSearchIndexCrawler.Result result =
                GboardSettingsSearchIndexCrawler.crawl(context);
        Assert.assertTrue("Settings pages failed to build while indexing: " + result.failures,
                result.failures.isEmpty());
        Assert.assertFalse(result.entries.isEmpty());

        String expected = render(result.entries);
        Path dataPath = Path.of(DATA_SOURCE);
        if (Boolean.parseBoolean(System.getProperty(UPDATE_PROPERTY))) {
            Files.write(dataPath, expected.getBytes(StandardCharsets.UTF_8));
            return;
        }
        String actual = Files.exists(dataPath)
                ? new String(Files.readAllBytes(dataPath), StandardCharsets.UTF_8)
                        .replace("\r\n", "\n")
                : "";
        Assert.assertEquals("The settings search index is stale; rerun this test with "
                + "-PupdateSettingsSearchIndex=true and commit " + DATA_SOURCE,
                expected, actual);
    }

    static String render(List<GboardSettingsSearchIndexCrawler.CrawledEntry> entries) {
        Map<String, Integer> pathIndexes = new LinkedHashMap<String, Integer>();
        List<List<String>> paths = new ArrayList<List<String>>();
        for (GboardSettingsSearchIndexCrawler.CrawledEntry entry : entries) {
            String key = String.join(">", entry.path);
            if (!pathIndexes.containsKey(key)) {
                pathIndexes.put(key, paths.size());
                paths.add(entry.path);
            }
        }

        StringBuilder source = new StringBuilder();
        source.append("package dev.jason.gboardpatches.extension.settings.search;\n")
                .append('\n')
                .append("import dev.jason.gboardpatches.extension.R;\n")
                .append('\n')
                .append("// Generated by GboardSettingsSearchIndexSnapshotTest; ")
                .append("do not edit by hand.\n")
                .append("final class GboardSettingsSearchIndexData {\n")
                .append("    private GboardSettingsSearchIndexData() {\n")
                .append("    }\n")
                .append('\n')
                .append("    /** Feature paths, see GboardSettingsSearchIndex#pathElement. */\n")
                .append("    static final String[][] PATHS = {\n");
        for (List<String> path : paths) {
            source.append("            {");
            for (int index = 0; index < path.size(); index++) {
                if (index > 0) {
                    source.append(",\n                    ");
                }
                source.append('"').append(path.get(index)).append('"');
            }
            source.append("},\n");
        }
        source.append("    };\n")
                .append('\n')
                .append("    /** {path index, title, summary or 0, 1 when the entry names ")
                .append("the page}. */\n")
                .append("    static final int[][] ENTRIES = {\n");
        for (GboardSettingsSearchIndexCrawler.CrawledEntry entry : entries) {
            source.append("            {")
                    .append(pathIndexes.get(String.join(">", entry.path)))
                    .append(", R.string.").append(entry.titleName)
                    .append(", ")
                    .append(entry.summaryName == null ? "0" : "R.string." + entry.summaryName)
                    .append(", ").append(entry.page ? 1 : 0)
                    .append("},\n");
        }
        source.append("    };\n")
                .append("}\n");
        return source.toString();
    }
}
